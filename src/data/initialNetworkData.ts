export interface CliProvisionParams {
  vendor: VendorType;
  ponPortLabel: string;
  onuIndex: number;
  serialNumber: string;
  model: string;
  customerName: string;
  serviceId: string;
  svlan: number;
  cvlan: number;
  lineProfile: string;
  serviceProfile: string;
  upMbps: number;
  downMbps: number;
  pppoeUser?: string;
}

export function generateVendorProvisioningCli(params: CliProvisionParams): string {
  const {
    vendor,
    ponPortLabel,
    onuIndex,
    serialNumber,
    model,
    customerName,
    serviceId,
    svlan,
    cvlan,
    lineProfile,
    serviceProfile,
    upMbps,
    downMbps,
  } = params;

  const cleanDesc = `${serviceId}_${customerName.replace(/\s+/g, '_')}`;
  const upKbps = upMbps * 1024;
  const downKbps = downMbps * 1024;

  if (vendor === 'ZTE') {
    const portNum = ponPortLabel.replace('gpon-olt_', '').replace('xgpon-olt_', '');
    return [
      `! --- ZTE ZXROS GPON Provisioning Script ---`,
      `configure terminal`,
      `interface gpon-olt_${portNum}`,
      `  onu ${onuIndex} type ${model.split(' ')[0] || 'ALL-ONT'} sn ${serialNumber}`,
      `exit`,
      `interface gpon-onu_${portNum}:${onuIndex}`,
      `  name ${cleanDesc}`,
      `  description ${customerName}`,
      `  sn-bind enable sn`,
      `  tcont 1 name TCONT_HSI profile DBA_${upMbps}M`,
      `  gemport 1 name GEM_HSI tcont 1`,
      `  gemport 1 traffic-limit upstream UP_${upMbps}M downstream DOWN_${downMbps}M`,
      `  service-port 1 vport 1 user-vlan ${cvlan} vlan ${svlan}`,
      `exit`,
      `pon-onu-mng gpon-onu_${portNum}:${onuIndex}`,
      `  service HSI gemport 1 vlan ${cvlan}`,
      `  wan-ip 1 mode pppoe username ${serviceId.toLowerCase()}@isp.id password ******** vlan-profile VLAN_${cvlan} host 1`,
      `  security-mgmt 1 state enable mode forward protocol web https`,
      `exit`,
      `write`,
    ].join('\n');
  }

  if (vendor === 'Huawei') {
    const parts = ponPortLabel.split('/');
    const frameSlot = parts.length >= 2 ? `${parts[0]}/${parts[1]}` : '0/1';
    const ponId = parts[2] || '0';
    return [
      `# --- Huawei MA5800 VRP GPON Provisioning Script ---`,
      `enable`,
      `config`,
      `dba-profile add profile-name DBA_${upMbps}M type4 max ${upKbps}`,
      `interface gpon ${frameSlot}`,
      `  ont add ${ponId} ${onuIndex} sn-auth "${serialNumber}" omci ont-lineprofile-name "${lineProfile}" ont-srvprofile-name "${serviceProfile}" desc "${cleanDesc}"`,
      `  ont ipconfig ${ponId} ${onuIndex} ip-index 1 pppoe vlan ${cvlan} priority 0 user-account username "${serviceId.toLowerCase()}@isp.id" password "********"`,
      `  ont internet-config ${ponId} ${onuIndex} ip-index 1`,
      `  ont policy-route-config ${ponId} ${onuIndex} profile-id 1`,
      `quit`,
      `service-port vlan ${svlan} gpon ${frameSlot}/${ponId} ont ${onuIndex} gemport 1 multi-service user-vlan ${cvlan} tag-transform translate-and-add inner-vlan ${cvlan} inbound traffic-table name UP_${upMbps}M outbound traffic-table name DOWN_${downMbps}M`,
      `save`,
    ].join('\n');
  }

  if (vendor === 'FiberHome') {
    const match = ponPortLabel.match(/slot-(\d+)\/pon-(\d+)/);
    const slotNo = match ? match[1] : '1';
    const ponNo = match ? match[2] : '1';
    return [
      `# --- FiberHome AN6000 / AN5516 GPON Provisioning Script ---`,
      `cd onu`,
      `set whitelist phy_addr address ${serialNumber} password null action add slot ${slotNo} pon ${ponNo} onu ${onuIndex} type ${model.split(' ')[0] || 'AN5506-04'}`,
      `set autorun_onu_name slot ${slotNo} pon ${ponNo} onu ${onuIndex} name ${cleanDesc}`,
      `cd ../pon`,
      `set onu_bw slot ${slotNo} pon ${ponNo} onu ${onuIndex} up_bw ${upKbps} down_bw ${downKbps}`,
      `cd ../service`,
      `set wan_connect slot ${slotNo} pon ${ponNo} onu ${onuIndex} index 1 mode route type internet vlan ${cvlan} cos 0 nat enable pppoe_mode auto username ${serviceId.toLowerCase()}@isp.id password ********`,
      `set qinq_svlan slot ${slotNo} pon ${ponNo} onu ${onuIndex} cvlan ${cvlan} svlan ${svlan}`,
      `cd ..`,
      `save`,
    ].join('\n');
  }

  // Nokia 7360 ISAM FX
  const nokiaBase = ponPortLabel || '1/1/1/1';
  return [
    `# --- Nokia 7360 ISAM FX GPON Provisioning Script ---`,
    `configure equipment ont interface ${nokiaBase}/${onuIndex} sw-ver-pland auto sernum ALCL:${serialNumber.replace('ALCL', '')} subslocid "${serviceId}" desc1 "${customerName}" admin-state up`,
    `configure equipment ont slot ${nokiaBase}/${onuIndex}/1 planned-card-type veip plndnumdataports 1 plndnumvoiceports 0 admin-state up`,
    `configure qos interface ${nokiaBase}/${onuIndex}/1/1 upstream-queue 0 bandwidth-profile name:UP_${upMbps}M`,
    `configure qos interface ${nokiaBase}/${onuIndex}/1/1 queue 0 shaper-profile name:DOWN_${downMbps}M`,
    `configure bridge port ${nokiaBase}/${onuIndex}/1/1 max-unicast-mac 16`,
    `configure bridge port ${nokiaBase}/${onuIndex}/1/1 vlan-id ${cvlan} network-vlan ${svlan} tag single-tagged`,
    `admin save`,
  ].join('\n');
}
